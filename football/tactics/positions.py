def preset_slots(name: str, team: int = 0) -> list:
    """取一套起点站位。team=1 时自动镜像到对侧半场。"""
    pts = PRESETS.get(name) or PRESETS["4-4-2"]
    out = []
    for pos, x, y in pts:
        if team == 1:
            out.append({"team": 1, "pos": pos, "x": round(1 - x, 4), "y": round(1 - y, 4)})
        else:
            out.append({"team": 0, "pos": pos, "x": x, "y": y})
    return out


def catalog() -> dict:
    """给前端的元数据：位置列表 + 模板列表。"""
    return {
        "positions": [{"code": k, "cn": v} for k, v in POSITIONS_CN.items()],
        "presets": list(PRESETS.keys()),
    }
